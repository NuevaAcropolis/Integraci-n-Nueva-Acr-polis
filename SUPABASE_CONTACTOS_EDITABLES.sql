-- Hace editables desde Acceso interno los contactos de Donaciones y Áreas.

create table if not exists public.configuracion_contactos (
  clave text primary key,
  nombre text not null,
  whatsapp text not null,
  updated_at timestamptz not null default now()
);

create table if not exists public.areas_contacto (
  id bigint generated by default as identity primary key,
  area_id text not null unique,
  encargado text not null default '',
  whatsapp text not null default '',
  updated_at timestamptz not null default now()
);

