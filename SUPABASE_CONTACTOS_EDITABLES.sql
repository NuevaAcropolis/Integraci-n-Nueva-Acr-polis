alter table public.configuracion_contactos enable row level security;
alter table public.areas_contacto enable row level security;

drop policy if exists "contactos lectura publica" on public.configuracion_contactos;
create policy "contactos lectura publica" on public.configuracion_contactos for select using (true);
drop policy if exists "areas lectura publica" on public.areas_contacto;
create policy "areas lectura publica" on public.areas_contacto for select using (true);

drop policy if exists "contactos admin update" on public.configuracion_contactos;
create policy "contactos admin update" on public.configuracion_contactos for all to authenticated
using (public.es_admin_actual()) with check (public.es_admin_actual());

drop policy if exists "areas admin update" on public.areas_contacto;
create policy "areas admin update" on public.areas_contacto for all to authenticated
using (public.es_admin_actual()) with check (public.es_admin_actual());

-- El encargado de donaciones también puede cambiar SU contacto de donaciones.
drop policy if exists "contactos donaciones responsable" on public.configuracion_contactos;
create policy "contactos donaciones responsable" on public.configuracion_contactos for update to authenticated
using (clave='donaciones' and exists (select 1 from public.mis_roles_actuales() r where r.rol='encargado_donaciones'))
with check (clave='donaciones' and exists (select 1 from public.mis_roles_actuales() r where r.rol='encargado_donaciones'));

grant select on public.configuracion_contactos, public.areas_contacto to anon, authenticated;
grant insert, update, delete on public.configuracion_contactos, public.areas_contacto to authenticated;
notify pgrst, 'reload schema';
